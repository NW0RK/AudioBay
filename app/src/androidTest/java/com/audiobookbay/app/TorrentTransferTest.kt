import timber.log.Timber
import kotlinx.serialization.json.Json
import org.junit.Assert.*
import org.junit.Test
import org.junit.runner.RunWith
import org.libtorrent4j.*
import java.io.File
import java.nio.ByteBuffer
import java.nio.ByteOrder

/** Transfers only audio generated by this test, between two local native sessions. */
@RunWith(AndroidJUnit4::class)
class TorrentTransferTest {
    @Test fun magnetTransferAndProcessRestartPreserveVerifiedAudio() = runBlocking {
        val app = InstrumentationRegistry.getInstrumentation().targetContext
        val testRoot = File(app.cacheDir, "torrent-test-${System.nanoTime()}").apply { mkdirs() }
        val files = File(testRoot, "state").apply { mkdirs() }
        val downloads = File(testRoot, "downloads").apply { mkdirs() }
        val testContext = object : ContextWrapper(app) {
            override fun getFilesDir() = files
            override fun getExternalFilesDir(type: String?) = downloads
            override fun startForegroundService(service: Intent): ComponentName = ComponentName(app, "TestService")
        }
        val db = Room.inMemoryDatabaseBuilder(app, AppDatabase::class.java).build()
        val seeder = SessionManager()
        var manager = TorrentDownloadManagerImpl(testContext, db.downloadDao(), Json, Dispatchers.IO)
        try {
            val seedDir = File(testRoot, "seed").apply { mkdirs() }
            val audio = File(seedDir, "lawful-test.wav")
            val pcm = ByteArray(1048576)
            val header = ByteBuffer.allocate(44).order(ByteOrder.LITTLE_ENDIAN)
                .put("RIFF".toByteArray()).putInt(36 + pcm.size).put("WAVEfmt ".toByteArray())
                .putInt(16).putShort(1.toShort()).putShort(1.toShort()).putInt(16000).putInt(32000)
                .putShort(2.toShort()).putShort(16.toShort()).put("data".toByteArray()).putInt(pcm.size).array()
            audio.writeBytes(header + pcm)
            val torrentBytes = TorrentBuilder().path(audio).pieceSize(16384).flags(TorrentBuilder.V1_ONLY).generate().entry().bencode()
            val info = TorrentInfo(torrentBytes)
            seeder.start(SessionParams(SettingsPack().listenInterfaces("127.0.0.1:47891").uploadRateLimit(32768).apply { setEnableDht(false); setEnableLsd(false) }))
            seeder.download(info, seedDir, null, null, null, TorrentFlags.SEED_MODE)
            withTimeout(15000) { while (seeder.find(info.infoHash())?.status()?.isSeeding != true) delay(200) }
            seeder.find(info.infoHash()).uploadLimit = 32768
            val magnet = "magnet:?xt=urn:btih:${info.infoHash().toHex()}&dn=lawful-test&x.pe=127.0.0.1:47891"
            val result = manager.startDownload("test-book", magnet, downloads, null).getOrThrow()
            withTimeoutOrNull(30000) {
                manager.observeDownload(result.infoHash).onEach { Timber.i("Local test transfer: $it") }
                    .first { it != null && it.bytesDownloaded > 0 && it.progress < 1f }
            } ?: error("No partial transfer observed: ${manager.observeDownload(result.infoHash).first()}")
            manager.pauseDownload(result.infoHash).getOrThrow()
            assertEquals(DownloadStatus.PAUSED, manager.observeDownload(result.infoHash).first()?.status)
            manager.shutdown()
            manager = TorrentDownloadManagerImpl(testContext, db.downloadDao(), Json, Dispatchers.IO)
            manager.initialize()
            assertEquals(DownloadStatus.PAUSED, manager.observeDownload(result.infoHash).first()?.status)
            manager.resumeDownload(result.infoHash).getOrThrow()
            val completed = withTimeout(60000) {
                manager.observeDownload(result.infoHash).first { it?.status == DownloadStatus.COMPLETED || it?.status == DownloadStatus.ERROR }
            }
            assertEquals(completed?.errorMessage, DownloadStatus.COMPLETED, completed?.status)
            assertArrayEquals(audio.readBytes(), File(downloads, audio.name).readBytes())
            manager.shutdown()
            manager = TorrentDownloadManagerImpl(testContext, db.downloadDao(), Json, Dispatchers.IO)
            manager.initialize()
            assertEquals(DownloadStatus.COMPLETED, manager.observeDownload(result.infoHash).first()?.status)
            assertTrue(File(files, "torrent-state/${result.infoHash}.resume").isFile)
        } finally {
            manager.shutdown()
            withContext(Dispatchers.IO) { seeder.stop() }
            db.close()
            // All test files are under the unique directory explicitly created above.
            testRoot.deleteRecursively()
        }
    }
}
